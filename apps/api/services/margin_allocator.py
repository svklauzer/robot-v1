"""Динамическое распределение маржи между готовыми кандидатами цикла.

Идея (по ТЗ Капитана): когда сетап прошёл ВСЕ гейты и готов к публикации,
система смотрит, сколько ещё кандидатов прошло гейты В ЭТОМ ЖЕ цикле, и делит
СВОБОДНУЮ маржу (потолок − уже открытые) поровну между ними. Если кандидат один —
он занимает всю свободную маржу (максимальный размер на готовую идею).

Чистая функция над числами (free_margin, num_ready) — без settings/ccxt/БД,
тестируется изолированно. Возвращает МАРЖУ на сделку (USDT); нотионал = маржа ×
плечо считает trade_plan (плечо — отдельная регулируемая ручка DYNAMIC_MARGIN_LEVERAGE).
"""
from __future__ import annotations


def per_trade_margin(free_margin: float, num_ready: int,
                     *, cap_pct_of_free: float = 1.0,
                     universe_size: int = 0, ceiling: float = 0.0) -> float:
    """Маржа (USDT) на одну готовую сделку этого цикла.

    free_margin   — свободная маржа сейчас: потолок(70% экв) − занятая открытыми.
    num_ready     — сколько кандидатов прошло ВСЕ гейты в этом цикле (>=1).
    cap_pct_of_free — верхний предохранитель на долю free на одну сделку.
    universe_size — сколько символов торгует бот (режим равной доли).
    ceiling       — потолок маржи (70% эквити), от которого делится доля.

    ── Режим РАВНОЙ ДОЛИ (#fair-share-2026-07-27) ────────────────────────────
    Прежнее правило «один готовый кандидат забирает ВСЮ свободную маржу»
    создавало гонку: первый прошедший гейты символ занимал весь потолок, и
    остальные упирались в `blocked_total_margin_limit` /
    `required_margin_exceeds_free_margin` — то есть отклонялись НЕ по качеству
    сетапа, а потому что деньги уже кто-то забрал. Кандидаты приходят не
    одновременно (разные ТФ, разное время подтверждения), поэтому «поровну
    между готовыми В ЭТОМ цикле» на практике почти всегда означало «всё одному».

    При universe_size > 0 доля считается от ПОТОЛКА и делится на размер
    вселенной, а не на число готовых сейчас:

        доля = min(ceiling / universe_size, free_margin)

    Тогда каждый символ гарантированно имеет свою часть капитала, сколько бы
    других уже ни открылось, и ни один сетап не отклоняется из-за денег.
    Ограничение free_margin оставлено: занять больше, чем реально свободно,
    нельзя.

    Прежнее поведение сохраняется при universe_size = 0 (обратная совместимость).
    """
    fm = float(free_margin)
    if fm <= 0:
        return 0.0

    uni = max(0, int(universe_size))
    ceil_ = float(ceiling or 0.0)
    if uni > 0 and ceil_ > 0:
        return round(max(0.0, min(ceil_ / uni, fm)), 6)

    n = max(1, int(num_ready))
    cap = max(0.0, min(float(cap_pct_of_free), 1.0))
    per = fm if n == 1 else fm / n
    per = min(per, fm * cap)          # предохранитель на одну сделку
    return round(max(0.0, per), 6)
