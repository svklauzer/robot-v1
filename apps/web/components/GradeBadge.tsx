// (#grade-axis-2026-09-04) Грейд — публичная метка, но НЕ ранжирование по
// результату. Замер по 97 закрытым сделкам говорит обратное тому, что рисовали
// цвета: A значимо убыточен (−0.4257R, ДИ [−0.75; −0.07]), B неотличим от нуля
// (+0.0103R). При этом confidence, по которой грейд и ставится, предсказывает
// СТОП: AUC 0.6605, ДИ [0.549; 0.772].
//
// Раньше A красился зелёным, B — жёлтым (предупреждение), C — красным. Это
// вердикт, и он был перевёрнут. Инвертировать палитру нельзя: B не «хорош», он
// у нуля — покрасить его зелёным значило бы заменить одно ложное утверждение
// другим. Поэтому цвет снят вовсе, а измерение переехало в подсказку.
//
// Компонент общий: до этой правки GradeBadge существовал в трёх копиях
// (signals, intelligence, reports), и правка палитры в одной из них оставила бы
// две страницы, продолжающие врать.

const MEASURED: Record<string, string> = {
  "A+": "Ожидание не измерено: наблюдений слишком мало.",
  A: "Замер 04.09 (97 сделок): ожидание −0.43R, ДИ [−0.75; −0.07] — значимо отрицательное.",
  B: "Замер 04.09 (97 сделок): ожидание +0.01R, ДИ [−0.34; +0.38] — неотличимо от нуля.",
  C: "Ожидание не измерено: наблюдений слишком мало.",
};

export default function GradeBadge({ grade }: { grade?: string | null }) {
  const key = (grade || "").toUpperCase();
  const measured = MEASURED[key] || "Ожидание не измерено.";

  return (
    <span
      title={`Грейд — метка отбора, а не оценка результата. ${measured}`}
      className="rounded-lg border border-slate-600 bg-slate-800 px-2 py-1 text-xs font-semibold text-slate-100"
    >
      {grade || "-"}
    </span>
  );
}
